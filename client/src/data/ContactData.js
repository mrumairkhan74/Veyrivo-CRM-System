// Helper Functions

// Get contacts by company ID
export const getContactsByCompany = (companyId) => {
  return ContactsData.filter(contact => contact.company_id === companyId);
};

// Get contacts by consent status
export const getContactsByConsentStatus = (status) => {
  return ContactsData.filter(contact => contact.consent_status === status);
};

// Get contacts by decision maker status
export const getDecisionMakers = () => {
  return ContactsData.filter(contact => contact.is_decision_maker === true);
};

// Search contacts
export const searchContacts = (query) => {
  const searchTerm = query.toLowerCase();
  return ContactsData.filter(contact => {
    const fullName = `${contact.first_name} ${contact.last_name}`.toLowerCase();
    return fullName.includes(searchTerm) ||
           contact.email?.toLowerCase().includes(searchTerm) ||
           contact.job_title?.toLowerCase().includes(searchTerm) ||
           contact.department?.toLowerCase().includes(searchTerm) ||
           contact.company?.name?.toLowerCase().includes(searchTerm) ||
           contact.phone?.includes(searchTerm);
  });
};

// Get recent contacts (last 30 days)
export const getRecentContacts = () => {
  const thirtyDaysAgo = new Date();
  thirtyDaysAgo.setDate(thirtyDaysAgo.getDate() - 30);
  
  return ContactsData.filter(contact => {
    const createdDate = new Date(contact.created_at);
    return createdDate >= thirtyDaysAgo;
  });
};

// Get contact by ID
export const getContactById = (id) => {
  return ContactsData.find(contact => contact.id === id);
};

// Get full name helper
export const getFullName = (contact) => {
  if (!contact) return 'Unknown';
  return `${contact.first_name || ''} ${contact.last_name || ''}`.trim() || 'Unknown';
};

// Get initials helper
export const getContactInitials = (contact) => {
  if (!contact) return '?';
  return `${contact.first_name?.[0] || ''}${contact.last_name?.[0] || ''}`.toUpperCase() || '?';
};

// Get contact statistics
export const getContactStats = () => {
  return {
    total: ContactsData.length,
    withCompanies: ContactsData.filter(c => c.company_id).length,
    withoutCompanies: ContactsData.filter(c => !c.company_id).length,
    decisionMakers: ContactsData.filter(c => c.is_decision_maker).length,
    optedIn: ContactsData.filter(c => c.consent_status === 'opted_in').length,
    optedOut: ContactsData.filter(c => c.consent_status === 'opted_out').length,
    unknownConsent: ContactsData.filter(c => c.consent_status === 'unknown').length
  };
};

// Get contacts by owner
export const getContactsByOwner = (ownerId) => {
  return ContactsData.filter(contact => contact.owner_id === ownerId);
};

// Get unique companies list from contacts
export const getUniqueCompanies = () => {
  const companyMap = new Map();
  ContactsData.forEach(contact => {
    if (contact.company_id && contact.company) {
      companyMap.set(contact.company_id, contact.company);
    }
  });
  return Array.from(companyMap.values());
};

// Get unique owners list from contacts
export const getUniqueOwners = () => {
  const ownerMap = new Map();
  ContactsData.forEach(contact => {
    if (contact.owner_id && contact.owner) {
      ownerMap.set(contact.owner_id, contact.owner);
    }
  });
  return Array.from(ownerMap.values());
};